"""Master timeline for YALMAVUZ (135 s): narration/creature placement, scene boundaries, events, word subtitles."""
import json, os, re
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
raw = json.load(open(os.path.join(ROOT, "data", "words_raw.json"), encoding="utf-8"))
DUR = 135.0
# clip -> (file, start, creature-voice stage 0..3 = how distorted the mimicked mother voice is)
CLIPS = {
    "s1": ("audio/raw/s1.mp3", 0.40, None), "s2": ("audio/raw/s2.mp3", 10.60, None),
    "m1": ("audio/raw/m1.mp3", 23.00, 0), "s3": ("audio/raw/s3.mp3", 25.60, None),
    "m1b": ("audio/raw/m1.mp3", 37.90, 1), "s4": ("audio/raw/s4.mp3", 38.90, None),
    "s5": ("audio/raw/s5.mp3", 52.30, None), "m2": ("audio/raw/m2.mp3", 66.30, 2),
    "s6": ("audio/raw/s6.mp3", 70.60, None), "s7": ("audio/raw/s7.mp3", 88.80, None),
    "m3": ("audio/raw/m3.mp3", 101.90, 3), "s8": ("audio/raw/s8.mp3", 109.60, None),
    "s9": ("audio/raw/s9.mp3", 119.60, None), "m4": ("audio/raw/m4.mp3", 133.00, 3),
}
CUT = {"m1b": 1.0}          # only "Oğlum…" of the m1 take is reused from behind him
SCENES = [(1, 0.0, 10.4), (2, 10.4, 22.9), (3, 22.9, 38.4), (4, 38.4, 51.7), (5, 51.7, 70.0), (6, 70.0, 88.6),
          (7, 88.6, 103.9), (8, 103.9, 119.4), (9, 119.4, 135.0)]
RED = {"yalmavuz", "yedi", "ölmüştü", "kaçıyorsun", "annemdi", "devasa", "yaratık", "ölü", "oğlum", "gel"}
RED_ONLY_IN = {"oğlum": {"m1", "m1b", "m2"}, "gel": {"m1", "m4"}}
norm = lambda w: re.sub(r"[^\wçğıöşüâî]", "", w.lower())
words = []
for clip, (f, off, stage) in CLIPS.items():
    for text, s, e in raw[clip]:
        n = norm(text)
        red = n in RED and (n not in RED_ONLY_IN or clip in RED_ONLY_IN[n])
        words.append({"text": text, "start": round(off + s, 3), "end": round(off + e, 3), "clip": clip, "red": red, "creature": stage is not None})
words.sort(key=lambda w: w["start"])
for i, w in enumerate(words):
    nxt = words[i + 1]["start"] if i + 1 < len(words) else DUR
    w["show_until"] = round(min(nxt, w["end"] + 0.45), 3)
EV = {
    "s1_eyes": 7.4, "s1_turn": 8.75, "s1_black": 9.3,
    "s2_stop": 19.0, "s2_shadow": [20.6, 22.8],
    "s3_sweep": [29.6, 34.0], "s3_hair": 34.6, "s3_behind": 37.9,
    "s4_child": 40.6, "s4_old": 43.2, "s4_all": [45.0, 50.6], "s4_silence": 50.7,
    "s5_hand": 52.4, "s5_body": 55.5, "s5_head1": 57.6, "s5_heads": [59.6, 63.4], "s5_turn": [63.5, 66.2], "s5_fall": 69.0,
    "s6_branch": [71.5, 73.2, 74.6], "s6_shake": 75.6, "s6_shadow": 78.0, "s6_fall": 80.6, "s6_heads": [82.4, 85.4], "s6_cabin": 85.6,
    "s7_slam": 88.7, "s7_knocks": [93.0, 93.75, 94.5], "s7_mother": 95.6, "s7_hide": 96.0, "s7_stop": 99.6, "s7_creak": 100.3,
    "s8_eyes": 103.9, "s8_look": [105.6, 107.0], "s8_faces": [107.0, 108.85], "s8_black": 108.9,
    "s8_window": 117.2, "s9_shadow": 123.5, "s9_turn": [127.0, 131.6], "s9_dark": 131.8, "title": [133.4, 134.9],
}
tl = {"duration": DUR, "fps": 24, "width": 1080, "height": 1920,
      "clips": {k: {"file": v[0], "start": v[1], "stage": v[2], "cut": CUT.get(k)} for k, v in CLIPS.items()},
      "scenes": [{"id": a, "start": b, "end": c} for a, b, c in SCENES], "events": EV, "words": words}
json.dump(tl, open(os.path.join(ROOT, "data", "timeline.json"), "w", encoding="utf-8"), ensure_ascii=False, indent=1)
open(os.path.join(ROOT, "render", "timeline.js"), "w", encoding="utf-8").write("// Generated by scripts/build_timeline.py\nwindow.TL = " + json.dumps(tl, ensure_ascii=False) + ";\n")
print(len(words), "words,", sum(w["red"] for w in words), "red; last word ends", max(w["end"] for w in words))
