"""Master timeline for DÂBBETÜ'L-ARZ (135 s): narration/creature placement, scene boundaries, events, word subtitles."""
import json, os, re
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
raw = json.load(open(os.path.join(ROOT, "data", "words_raw.json"), encoding="utf-8"))
DUR = 135.0
CK = 1 / (0.74 * 1.17)          # creature voice is pitched down (asetrate 0.74) and only partly re-tempoed (atempo 1.17)
# clip -> (file, start, creature?)
CLIPS = {
    "s1": ("audio/raw/s1.mp3", 0.5, False), "s2": ("audio/raw/s2.mp3", 14.9, False), "s3": ("audio/raw/s3.mp3", 28.7, False),
    "c1": ("audio/raw/c1.mp3", 39.9, True), "s4": ("audio/raw/s4.mp3", 42.3, False), "s5": ("audio/raw/s5.mp3", 55.5, False),
    "s6": ("audio/raw/s6.mp3", 69.9, False), "c2": ("audio/raw/c2.mp3", 82.5, True), "s7": ("audio/raw/s7.mp3", 90.0, False),
    "s8": ("audio/raw/s8.mp3", 104.0, False), "c1b": ("audio/raw/c1.mp3", 115.6, True), "s9": ("audio/raw/s9.mp3", 120.6, False),
}
SCENES = [(1, 0.0, 14.6), (2, 14.6, 28.4), (3, 28.4, 41.9), (4, 41.9, 55.2), (5, 55.2, 69.6), (6, 69.6, 89.6), (7, 89.6, 101.6), (8, 101.6, 120.0), (9, 120.0, 135.0)]
RED = {"kıyamet", "dâbbetülarz", "dâbbetülarzı", "toprak", "toprağın", "yaratık", "konuşacağı", "kaçmak", "mehmet", "kaçabilir"}
norm = lambda w: re.sub(r"[^\wçğıöşüâî]", "", w.lower())
words = []
for clip, (f, off, cr) in CLIPS.items():
    for text, s, e in raw[clip.rstrip("b") if clip == "c1b" else clip]:
        k = CK if cr else 1.0
        words.append({"text": text, "start": round(off + s * k, 3), "end": round(off + e * k, 3), "clip": clip, "red": norm(text) in RED, "creature": cr})
words.sort(key=lambda w: w["start"])
for i, w in enumerate(words):
    nxt = words[i + 1]["start"] if i + 1 < len(words) else DUR
    w["show_until"] = round(min(nxt, w["end"] + 0.45), 3)
EV = {
    "s1_earth": 1.6, "s1_stones": 5.0, "s1_under": 8.0, "s1_eyes": 11.2, "s1_shake": 13.3, "s1_black": 14.1,
    "s2_fly": 14.6, "s2_slide": 19.5, "s2_window": 22.0, "s2_glass": 24.6, "s2_boom": 27.0,
    "s3_walk": 28.4, "s3_cracks": 31.8, "s3_dust": 34.4, "s3_cave": 37.0, "s3_name": 39.9,
    "s4_freeze": 41.9, "s4_eyes_cu": 43.2, "s4_sweep": 45.2, "s4_breath": 46.2, "s4_rocks": 47.6, "s4_eyes": 50.3, "s4_sink": 52.6, "s4_rush": 53.9,
    "s5_crack": 55.2, "s5_dust": 57.8, "s5_limb": 58.1, "s5_fall": 59.6, "s5_rise": 61.0, "s5_eyes": 66.4, "s5_still": 69.0,
    "s6_face": 69.6, "s6_sit": 72.3, "s6_glow": 74.0, "s6_silence": 81.6, "s6_lower": 79.5, "s6_eyes_cu": 76.4,
    "s7_up": 89.6, "s7_side": 90.6, "s7_out": 92.4, "s7_rocks": 93.6, "s7_forest": 95.0, "s7_lights": 96.3, "s7_back": 99.3,
    "s8_morning": 101.6, "s8_return": 104.0, "s8_closed": 105.6, "s8_tracks": 107.8, "s8_kneel": 111.0, "s8_voice": 115.6, "s8_black": 117.4,
    "s9_earth": 120.0, "s9_down": 122.4, "s9_eyes": 125.8, "s9_sil": 128.0, "s9_dark": 131.0, "title": [132.4, 134.8],
}
tl = {"duration": DUR, "fps": 24, "width": 1080, "height": 1920, "ck": CK,
      "clips": {k: {"file": v[0], "start": v[1], "creature": v[2]} for k, v in CLIPS.items()},
      "scenes": [{"id": a, "start": b, "end": c} for a, b, c in SCENES], "events": EV, "words": words}
json.dump(tl, open(os.path.join(ROOT, "data", "timeline.json"), "w", encoding="utf-8"), ensure_ascii=False, indent=1)
open(os.path.join(ROOT, "render", "timeline.js"), "w", encoding="utf-8").write("// Generated by scripts/build_timeline.py\nwindow.TL = " + json.dumps(tl, ensure_ascii=False) + ";\n")
ends = {k: round(max(w["end"] for w in words if w["clip"] == k), 2) for k in CLIPS}
print(len(words), "words,", sum(w["red"] for w in words), "red; clip ends", ends)
