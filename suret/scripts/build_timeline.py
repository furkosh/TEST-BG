"""Master timeline for KONYA EREĞLİ – KAPIDAKİ SURET (120 s): narration placement, scenes, events, word subtitles."""
import json, os, re
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
raw = json.load(open(os.path.join(ROOT, "data", "words_raw.json"), encoding="utf-8"))
DUR = 120.0
CLIPS = {  # clip -> (file, start, voice)
    "n1": ("audio/raw/n1.mp3", 1.2, "narrator"), "w2": ("audio/raw/w2.mp3", 20.8, "wife"), "w3": ("audio/raw/w3.mp3", 35.2, "wife"),
    "w4": ("audio/raw/w4.mp3", 49.0, "wife"), "w5": ("audio/raw/w5.mp3", 63.3, "wife"), "w6": ("audio/raw/w6.mp3", 77.3, "wife"),
    "w7": ("audio/raw/w7.mp3", 90.0, "wife"), "n8": ("audio/raw/n8.mp3", 102.0, "narrator"),
}
SCENES = [(1, 0.0, 20.0), (2, 20.0, 34.5), (3, 34.5, 48.5), (4, 48.5, 62.5), (5, 62.5, 76.5), (6, 76.5, 89.5), (7, 89.5, 101.5), (8, 101.5, 120.0)]
RED = {"korkunç", "kapısında", "eşini", "uyuyordu", "kapıya", "eşimin", "yüzünü", "korkuyordum", "güvende", "sureti", "unutamadım", "benzerini", "yapardınız"}


def norm(w):
    w = w.replace("İ", "i").replace("I", "ı").lower()
    return re.sub(r"[^a-zçğıöşüâî0-9]", "", w)


words = []
for clip, (f, off, voice) in CLIPS.items():
    for text, s, e in raw[clip]:
        words.append({"text": text, "start": round(off + s, 3), "end": round(off + e, 3), "clip": clip, "red": norm(text) in RED, "voice": voice})
words.sort(key=lambda w: w["start"])
for i, w in enumerate(words):
    nxt = words[i + 1]["start"] if i + 1 < len(words) else DUR
    w["show_until"] = round(min(nxt, w["end"] + 0.45), 3)
EV = {
    # S1 intro
    "card": [1.3, 4.2], "street": 4.4, "window": 7.2, "eyes1": 10.0, "eyes1_open": 10.96, "corr1": 11.9, "sil": 13.3, "eyes2": 15.5, "husb1": 16.4,
    "black1": 18.35, "title": [18.7, 19.9],
    # S2 first night
    "wide2": 20.0, "face2": 21.8, "open2": 21.98, "door2": 25.1, "reveal2": 26.3, "dbl2": 27.2, "dblcu2": 30.5, "react2": 32.2,
    # S3 the second likeness
    "look3": 34.5, "husb3": 36.4, "rack3": [38.9, 39.8], "dblcu3": 40.8, "smile3": [41.6, 42.8], "scream3": 43.0, "door3": 46.3, "flick3": [47.0, 47.6],
    # S4 endless nights
    "sit4": 48.5, "situp4": 49.0, "shadow4": 52.0, "kdoor4": 55.0, "kopen4": [55.4, 57.8], "window4": 58.0,
    # S5 escape
    "pack5": 62.5, "look5": 65.9, "corr5": 67.4, "car5": 68.6, "drive5": [69.2, 72.2], "win5": 72.0, "shadow5": [73.8, 75.6],
    # S6 return
    "back6": 76.5, "card6": [77.0, 79.8], "door6": 80.4, "dopen6": [80.6, 82.4], "face6": 82.9, "close6": [83.9, 84.7], "flash6": 85.3, "open6": 87.6,
    # S7 call for help
    "table7": 89.5, "tears7": 92.9, "news7": 95.3, "news7b": 97.4, "face7": 99.4,
    # S8 final
    "wide8": 101.5, "appear8": [113.6, 114.8], "dbl8": 113.6, "cu8": 116.3, "scare8": 117.9, "black8": 118.35, "end8": [118.9, 120.0],
}
tl = {"duration": DUR, "fps": 24, "width": 1080, "height": 1920,
      "clips": {k: {"file": v[0], "start": v[1], "voice": v[2]} for k, v in CLIPS.items()},
      "scenes": [{"id": a, "start": b, "end": c} for a, b, c in SCENES], "events": EV, "words": words}
json.dump(tl, open(os.path.join(ROOT, "data", "timeline.json"), "w", encoding="utf-8"), ensure_ascii=False, indent=1)
open(os.path.join(ROOT, "render", "timeline.js"), "w", encoding="utf-8").write("// Generated by scripts/build_timeline.py\nwindow.TL = " + json.dumps(tl, ensure_ascii=False) + ";\n")
ends = {k: round(max(w["end"] for w in words if w["clip"] == k), 2) for k in CLIPS}
print(len(words), "words,", sum(w["red"] for w in words), "red:", sorted({w['text'] for w in words if w['red']}), "\nclip ends", ends)
