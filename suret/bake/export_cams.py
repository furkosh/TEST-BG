"""Write render/bg/cams.js: the pinhole camera of every baked view at its final plate size (for live 3D projection)."""
import json, math, os
import numpy as np
from rt import camera
import bake_view as B

SCALES = {'aerial': 1.25, 'bed_wide': 1.6, 'ext_side_n': 1.5, 'corridor_dawn': 1.0}
out = {}
for name, V in B.VIEWS.items():
    sc = SCALES.get(name, 1.25)
    w, h = int(round(1080 * sc)), int(round(1920 * sc))
    f = (w / 2) / math.tan(math.radians(V['fov'] / 2))
    cam = camera(V['pos'], V['target'], f, w, h, V.get('roll', 0.0), V.get('up', (0.0, 1.0, 0.0)))
    out[name] = {'pos': cam[0:3].tolist(), 'fw': cam[3:6].tolist(), 'rt': cam[6:9].tolist(), 'up': cam[9:12].tolist(), 'f': f, 'w': w, 'h': h}
open(os.path.join(B.OUT_DIR, 'cams.js'), 'w').write('// generated by bake/export_cams.py\nwindow.CAMS = ' + json.dumps(out) + ';\n')
print('cams for', len(out), 'views')
