"""Prepare the face mesh for the renderer: Loop-subdivide the MediaPipe canonical face (Apache-2.0) once,
recompute normals and export to render/facemesh.js (cm, y up, z toward the viewer)."""
import json, os
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
OBJ = os.path.join(HERE, 'third_party', 'canonical_face_model.obj')


def load(fn):
    V, F = [], []
    for l in open(fn):
        if l.startswith('v '):
            V.append([float(a) for a in l.split()[1:4]])
        elif l.startswith('f '):
            F.append([int(a.split('/')[0]) - 1 for a in l.split()[1:4]])
    return np.array(V), np.array(F)


def loop_subdivide(V, F):
    edges = {}
    def ekey(a, b): return (a, b) if a < b else (b, a)
    eface = {}
    for fi, (a, b, c) in enumerate(F):
        for (p, q, r) in ((a, b, c), (b, c, a), (c, a, b)):
            eface.setdefault(ekey(p, q), []).append(r)
    nbr = [set() for _ in range(len(V))]
    for (a, b) in eface:
        nbr[a].add(b); nbr[b].add(a)
    boundary = {e for e, opp in eface.items() if len(opp) == 1}
    bnbr = [set() for _ in range(len(V))]
    for (a, b) in boundary:
        bnbr[a].add(b); bnbr[b].add(a)
    NV = [v.copy() for v in V]
    # new edge points
    eidx = {}
    for e, opp in eface.items():
        a, b = e
        if len(opp) == 2:
            p = 0.375 * (V[a] + V[b]) + 0.125 * (V[opp[0]] + V[opp[1]])
        else:
            p = 0.5 * (V[a] + V[b])
        eidx[e] = len(NV); NV.append(p)
    # reposition old vertices
    for i in range(len(V)):
        if bnbr[i]:
            if len(bnbr[i]) == 2:
                a, b = list(bnbr[i])
                NV[i] = 0.75 * V[i] + 0.125 * (V[a] + V[b])
            continue
        n = len(nbr[i])
        if n < 3:
            continue
        beta = (1 / n) * (5 / 8 - (3 / 8 + 0.25 * np.cos(2 * np.pi / n)) ** 2)
        NV[i] = (1 - n * beta) * V[i] + beta * sum(V[j] for j in nbr[i])
    NF = []
    for (a, b, c) in F:
        ab, bc, ca = eidx[ekey(a, b)], eidx[ekey(b, c)], eidx[ekey(c, a)]
        NF += [[a, ab, ca], [b, bc, ab], [c, ca, bc], [ab, bc, ca]]
    return np.array(NV), np.array(NF)


V, F = load(OBJ)
V2, F2 = loop_subdivide(V, F)
print('verts', len(V), '->', len(V2), 'tris', len(F), '->', len(F2))
out = {'v': np.round(V2, 4).flatten().tolist(), 'f': F2.flatten().tolist(), 'n0': len(V)}
dst = os.path.join(os.path.dirname(HERE), 'render', 'facemesh.js')
open(dst, 'w').write('// MediaPipe canonical face mesh (Apache-2.0), Loop-subdivided once. Generated by bake/facemesh.py\nwindow.FACEMESH = ' + json.dumps(out, separators=(',', ':')) + ';\n')
print('wrote', dst, os.path.getsize(dst), 'bytes')
# key landmarks (original indices) for reference
for name, i in [('nose_tip', 1), ('chin', 152), ('forehead', 10), ('eyeR_out', 33), ('eyeR_in', 133), ('eyeL_in', 362), ('eyeL_out', 263),
                ('lip_top', 0), ('lip_in_up', 13), ('lip_in_lo', 14), ('lip_bot', 17), ('mouthR', 61), ('mouthL', 291), ('upLidR', 159), ('loLidR', 145)]:
    print(name, i, np.round(V2[i], 2))
