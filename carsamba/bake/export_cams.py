"""Write render/bg/cams.js: the pinhole camera of every baked view at its final plate size (for live 3D projection)."""
import json, math, os
import numpy as np
from rt import camera
import bake_view as B

SCALES = {}
out = {}
for name, V in B.VIEWS.items():
    sc = SCALES.get(name, 1.25)
    w, h = int(round(1080 * sc)), int(round(1920 * sc))
    f = (w / 2) / math.tan(math.radians(V['fov'] / 2))
    cam = camera(V['pos'], V['target'], f, w, h, V.get('roll', 0.0), V.get('up', (0.0, 1.0, 0.0)))
    out[name] = {'pos': cam[0:3].tolist(), 'fw': cam[3:6].tolist(), 'rt': cam[6:9].tolist(), 'up': cam[9:12].tolist(), 'f': f, 'w': w, 'h': h}
open(os.path.join(B.OUT_DIR, 'cams.js'), 'w').write('// generated by bake/export_cams.py\nwindow.CAMS = ' + json.dumps(out) + ';\n')
print('cams for', len(out), 'views')

# street layout (doors, upper windows) for live props: closing doors and shutters, villagers
import numpy as np
import village as Vg
houses = []
_orig = Vg.ottoman_house
def _rec(S, side, z0, z1, upper='lime', lit=(), door=True, rng=None, depth=7.0):
    nw = 2 if (z1 - z0) < 6.5 else 3
    houses.append({'side': side, 'z0': z0, 'z1': z1, 'door': (z0 + z1) / 2 + 0.6, 'lit': list(lit),
                   'wins': [z0 + (k + 0.5) * (z1 - z0) / nw for k in range(nw)]})
    return _orig(S, side, z0, z1, upper, lit, door, rng, depth)
Vg.ottoman_house = _rec
for lit in (0.15, 0.4):
    houses.clear(); S = Vg.new_scene(); Vg.street(S, np.random.default_rng(3), lit_windows=lit)
    with open(os.path.join(B.OUT_DIR, 'cams.js'), 'a') as fh:
        fh.write(f'window.HOUSES_{int(lit * 100)} = ' + json.dumps(houses) + ';\n')
print('houses', len(houses))
