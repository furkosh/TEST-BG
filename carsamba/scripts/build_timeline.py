"""Master timeline for ÇARŞAMBA KARISI – 30 s viral intro: narration placement, scenes, events, word subtitles."""
import json, os, re
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
proc = json.load(open(os.path.join(ROOT, "data", "words.json"), encoding="utf-8"))
DUR = 30.0
CLIPS = {  # clip -> (file, start, voice)
    "v1": ("audio/build/v1.wav", 0.20, "narrator"), "v2": ("audio/build/v2.wav", 4.14, "narrator"),
    "v3": ("audio/build/v3.wav", 9.64, "narrator"), "v4": ("audio/build/v4.wav", 15.66, "narrator"),
    "v5": ("audio/build/v5.wav", 21.75, "narrator"), "k1": ("audio/build/k1_door.wav", 27.80, "creature"),
}
# the muffled line behind the door is not transcribed: word spans measured from its energy envelope
K1 = [("Bitmedi", 0.12, 0.66), ("mi", 0.68, 0.92), ("işin?", 1.0, 1.8)]
SCENES = [(1, 0.0, 4.1), (2, 4.1, 9.6), (3, 9.6, 15.6), (4, 15.6, 21.6), (5, 21.6, 26.45), (6, 26.45, 30.0)]
RED = {"çarşamba", "korkunç", "gazabından", "karısı", "insanüstü", "iplik", "bitmedi"}


def norm(w):
    w = w.replace("İ", "i").replace("I", "ı").lower()
    return re.sub(r"[^a-zçğıöşüâî0-9]", "", w)


words = []
for clip, (f, off, voice) in CLIPS.items():
    src = K1 if clip == "k1" else [(w["w"], w["s"], w["e"]) for w in proc["words"][clip]]
    for text, s, e in src:
        words.append({"text": text, "start": round(off + s, 3), "end": round(off + e, 3), "clip": clip, "red": norm(text) in RED,
                      "voice": voice, "creature": voice == "creature"})
words.sort(key=lambda w: w["start"])
for i, w in enumerate(words):
    nxt = words[i + 1]["start"] if i + 1 < len(words) else DUR
    w["show_until"] = round(min(nxt, w["end"] + 0.35), 3)
EV = {
    # S1 chase
    "run": 0.0, "low": 1.40, "crash": 2.55, "hit1": 4.0,
    # S2 the door
    "door": 4.10, "pounds": [4.28, 4.62, 4.97, 5.33, 5.86, 6.2], "front": 5.75, "steps_stop": 6.45, "appear": 7.45, "scare": 8.0,
    "black2": 8.3, "far": 8.75,
    # S3 origin of the legend
    "village": 9.6, "card": [9.85, 11.75], "dusk": 11.95, "door3": 12.55, "windows": 13.85, "lightsout": [14.35, 14.9],
    # S4 the creature
    "tilt": 15.6, "tilt2": 17.6, "rush": 18.85, "empty": 19.3, "title": [20.3, 21.25],
    # S5 the spinning woman
    "room": 21.6, "silhouette": 22.55, "spindle": 23.55, "fire": 24.32, "react": 24.55, "bolt": 25.0, "rattle": [25.12, 25.62],
    # S6 transition
    "eyes": 26.45, "music_cut": 26.55, "knocks": [26.6, 26.93, 27.26], "voice": 27.92, "black": 29.72,
}
tl = {"duration": DUR, "fps": 24, "width": 1080, "height": 1920,
      "clips": {k: {"file": v[0], "start": v[1], "voice": v[2]} for k, v in CLIPS.items()},
      "scenes": [{"id": a, "start": b, "end": c} for a, b, c in SCENES], "events": EV, "words": words}
json.dump(tl, open(os.path.join(ROOT, "data", "timeline.json"), "w", encoding="utf-8"), ensure_ascii=False, indent=1)
open(os.path.join(ROOT, "render", "timeline.js"), "w", encoding="utf-8").write("// Generated by scripts/build_timeline.py\nwindow.TL = " + json.dumps(tl, ensure_ascii=False) + ";\n")
print(len(words), "words,", sum(w["red"] for w in words), "red:", sorted({w['text'] for w in words if w['red']}))
