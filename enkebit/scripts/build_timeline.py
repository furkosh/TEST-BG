"""Build the master timeline (narration placement, scenes, events, word-level subtitles).

Output: data/timeline.json and render/timeline.js (same data for the browser renderer).
All times are absolute seconds on the 120 s video timeline.
"""
import json, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
words_raw = json.load(open(os.path.join(ROOT, "data", "words_raw.json"), encoding="utf-8"))

DURATION = 120.0
FPS = 24

# Narration clip -> (file, start time on the timeline)
CLIPS = {
    "s1":  ("audio/raw/s1_a.mp3", 0.35),
    "s2":  ("audio/raw/s2_b.mp3", 12.50),
    "s3":  ("audio/raw/s3_b.mp3", 26.60),
    "s4":  ("audio/raw/s4_a.mp3", 43.40),
    "s5":  ("audio/raw/s5_b.mp3", 61.20),
    "s6a": ("audio/raw/s6a_a.mp3", 81.20),
    "cr":  ("audio/raw/cr_a.mp3", 90.80),
    "s6b": ("audio/raw/s6b_a.mp3", 94.20),
    "s7":  ("audio/raw/s7_b.mp3", 101.00),
    "s8":  ("audio/raw/s8_a.mp3", 112.30),
}

SCENES = [
    {"id": 1, "name": "Boğaz Deşen'in efsanesi", "start": 0.0,   "end": 10.2},
    {"id": 2, "name": "O gece",                   "start": 10.2,  "end": 25.4},
    {"id": 3, "name": "Yatağın altındaki ses",     "start": 25.4,  "end": 42.6},
    {"id": 4, "name": "Hareket edemiyorum",        "start": 42.6,  "end": 60.0},
    {"id": 5, "name": "Enkebit ortaya çıkıyor",    "start": 60.0,  "end": 80.0},
    {"id": 6, "name": "Boğaz Deşen",               "start": 80.0,  "end": 100.6},
    {"id": 7, "name": "Sabahın ilk ışıkları",      "start": 100.6, "end": 112.0},
    {"id": 8, "name": "Son iz",                    "start": 112.0, "end": 120.0},
]

# Horror-emphasis words (shown red, upper-case). Matched on the lower-cased word without punctuation.
RED = {"enkebit", "boğaz", "deşen", "tak", "tırnağıyla", "kımıldayamadım", "doğrulduğunu",
       "değildi", "gözlerini", "kapatma", "tırnağının", "öleceğimi", "üç", "tırnak", "izi",
       "kilitlemiştim"}
# Words whose red emphasis applies only in a given clip (avoid over-using red)
RED_ONLY_IN = {"nefes": "s3", "çöktü": "s5"}

def norm(w):
    return re.sub(r"[^\wçğıöşüâî]", "", w.lower())

words = []
for clip, (_, off) in CLIPS.items():
    for text, s, e in words_raw[clip]:
        n = norm(text)
        red = n in RED or RED_ONLY_IN.get(n) == clip
        words.append({"text": text, "start": round(off + s, 3), "end": round(off + e, 3),
                      "clip": clip, "red": red, "creature": clip == "cr"})
words.sort(key=lambda w: w["start"])
# display window: from word start until the next word starts (max 0.45 s hold after the word ends)
for i, w in enumerate(words):
    nxt = words[i + 1]["start"] if i + 1 < len(words) else DURATION
    w["show_until"] = round(min(nxt, w["end"] + 0.45), 3)

# Sound/visual sync events (absolute seconds)
EVENTS = {
    "s1_eyes_open": 5.0, "s1_scratch": 7.0, "s1_turn": 9.05, "s1_black": 9.45,
    "s3_candle_out": 26.0,
    "knocks": [29.50, 30.16, 30.72],
    "s3_scratch": [31.75, 34.3],
    "s3_eyes_open": 34.62,
    "s3_breath": 39.55,
    "s4_moan": 44.6, "s4_blanket": 49.6, "s4_rise": [53.0, 59.6],
    "s5_cuts": [60.0, 64.4, 66.8, 70.3, 72.6, 80.0],
    "s5_climb": 70.4, "s5_settle": 73.4,
    "s6_whisper": 90.8, "s6_trace": [94.0, 98.6], "s6_black": [98.8, 100.6],
    "s7_gasp": 100.6,
    "s8_scratches": 113.4, "s8_silhouette": 116.3, "s8_black": 118.55,
    "title": [118.9, 120.0], "final_scrape": 119.05,
}

tl = {"duration": DURATION, "fps": FPS, "width": 1080, "height": 1920,
      "clips": {k: {"file": v[0], "start": v[1]} for k, v in CLIPS.items()},
      "scenes": SCENES, "events": EVENTS, "words": words}

json.dump(tl, open(os.path.join(ROOT, "data", "timeline.json"), "w", encoding="utf-8"), ensure_ascii=False, indent=1)
with open(os.path.join(ROOT, "render", "timeline.js"), "w", encoding="utf-8") as f:
    f.write("// Generated by scripts/build_timeline.py - do not edit by hand\n")
    f.write("window.TL = " + json.dumps(tl, ensure_ascii=False) + ";\n")
print(len(words), "words;", sum(w["red"] for w in words), "red")
for w in words:
    if w["red"]:
        print(f'  {w["start"]:7.2f} {w["text"]}')
